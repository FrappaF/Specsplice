import type { ModelView, SemanticElement } from '../../../src/vs/workbench/contrib/ordito/common/modelTypes.ts';
import type { SmokeHarness } from './harness.ts';
import assert from 'node:assert/strict';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import path from 'node:path';
import { clickOrditoButton, closeCanvasActions, revealOrditoText, openAiSettings, chooseOrditoDiagram, openDiagramNavigation, openModelFile, openProperties, enterValue, chooseFolder, addElement, connect, runCommand } from './helpers.ts';

export function createBasicScenarios(harness: SmokeHarness) {
	const { launch, evidence, modelFile, emptyFile, invalidFile, checkoutModel, workspace, args, validateSemanticModel } = harness;
	return {
		async checkBasicWorkflow() {
			let window = await launch();
			let shell = window.locator('.ordito-shell');
			let sidebar = window.locator('.ordito-sidebar');
			const canvasNode = (name: string) => shell.locator('.ordito-canvas').getByRole('button', { name, exact: true });
			const clickUncoveredNode = async (name: string) => {
				const close = shell.getByRole('button', { name: 'Close Properties', exact: true });
				if (await close.isVisible()) { await close.click(); }
				await canvasNode(name).click();
			};
			await sidebar.waitFor();
			assert.equal(await window.locator('.explorer-viewlet:visible').count(), 0);
			await clickOrditoButton(window, 'Explore Purchase Example');
			await sidebar.locator('section[aria-label="Confirm Purchase"]')
				.getByRole('button', { name: 'Checkout Structure', exact: true }).click();
			await openModelFile(window, modelFile);
			const collaboration = await openAiSettings(window);
			for (const name of ['Choose Diagram Model', 'Connect Claude Code or Codex', 'Refresh Account and Models']) {
				assert.equal(await collaboration.getByRole('button', { name, exact: true }).isEnabled(), true);
			}
			assert.equal(await collaboration.getByRole('button', { name: 'Open AI CLI', exact: true }).count(), 0);
			await collaboration.getByRole('button', { name: 'Connect Claude Code or Codex', exact: true }).click();
			await window.locator('.quick-input-widget').getByText('Choose AI CLI', { exact: true }).waitFor();
			await window.locator('.quick-input-widget').getByText('Codex', { exact: true }).waitFor();
			await window.locator('.quick-input-widget').getByText('Claude Code', { exact: true }).waitFor();
			await window.keyboard.press('Escape');
			await window.locator('.quick-input-widget').waitFor({ state: 'hidden' });
			await window.screenshot({ path: path.join(evidence, 'ai-collaboration.png') });
			await runCommand(window, 'Specsplice: Return to Model');
			await window.locator('.quick-input-widget').waitFor({ state: 'hidden' });
			await shell.getByRole('region', { name: 'Diagram: Checkout Structure', exact: true }).waitFor();
			console.log('PASS: native AI controls and provider chooser render without inference; implementation, tests, apply and undo require an imported project or reviewed session.');
			await clickUncoveredNode('Request Payment');
			await openProperties(window);
			await shell.locator('.ordito-properties').getByRole('heading', { name: 'Request Payment', exact: true }).waitFor();
			await sidebar.getByRole('button', { name: 'Cart Structure', exact: true }).click();
			await shell.getByRole('region', { name: 'Diagram: Cart Structure', exact: true }).waitFor();
			await clickUncoveredNode('Cart');
			await sidebar.getByRole('button', { name: 'Checkout Structure', exact: true }).click();
			await openProperties(window);
			await shell.locator('.ordito-properties').getByRole('heading', { name: 'Request Payment', exact: true }).waitFor();
			await sidebar.getByRole('button', { name: 'Payment Outcome', exact: true }).click();
			const declined = shell.locator('.ordito-canvas').getByRole('button', { name: 'Payment Declined', exact: true });
			await declined.focus();
			await window.keyboard.press('Enter');
			assert.equal(await declined.getAttribute('aria-pressed'), 'true');
			assert.equal(await declined.evaluate(element => element === document.activeElement), true);
			await revealOrditoText(window, 'Transition Table: Order');
			await shell.getByRole('table', { name: 'Transition Table: Order', exact: true }).getByText('payment not authorized', { exact: true }).waitFor();
			await clickOrditoButton(window, 'Files');
			await window.locator('.explorer-viewlet').waitFor();
			await runCommand(window, 'Specsplice: Return to Model');
			await shell.getByRole('region', { name: 'Diagram: Payment Outcome', exact: true }).waitFor();
			assert.deepEqual([await shell.locator('.ordito-canvas').isVisible(), await declined.getAttribute('aria-pressed')], [true, 'true'], 'Return to Model restores the canvas and selection before reopening navigation');
			await openDiagramNavigation(window);
			await sidebar.waitFor();
			await shell.locator('.ordito-properties').getByRole('heading', { name: 'Payment Declined', exact: true }).waitFor();
			for (const [name, selector] of [['Debug', '.debug-viewlet'], ['Git', '.scm-viewlet']]) {
				await clickOrditoButton(window, name);
				await window.locator(selector).waitFor();
				await runCommand(window, 'Specsplice: Return to Model');
				await shell.getByRole('region', { name: 'Diagram: Payment Outcome', exact: true }).waitFor();
				assert.deepEqual([await shell.locator('.ordito-canvas').isVisible(), await declined.getAttribute('aria-pressed')], [true, 'true'], `${name}: Return to Model restores the canvas and selection before reopening navigation`);
				await openDiagramNavigation(window);
				await sidebar.waitFor();
				await shell.locator('.ordito-properties').getByRole('heading', { name: 'Payment Declined', exact: true }).waitFor();
			}
			await window.screenshot({ path: path.join(evidence, 'visual-workbench.png') });
			await harness.app.close();
			harness.app = undefined;
			window = await launch();
			shell = window.locator('.ordito-shell');
			sidebar = window.locator('.ordito-sidebar');
			await sidebar.waitFor();
			await shell.getByRole('region', { name: 'Diagram: Payment Outcome', exact: true }).waitFor();
			await openProperties(window);
			await shell.locator('.ordito-properties').getByRole('heading', { name: 'Payment Declined', exact: true }).waitFor();
			await chooseOrditoDiagram(window, 'Cart Structure');
			await openProperties(window);
			await shell.locator('.ordito-properties').getByRole('heading', { name: 'Cart', exact: true }).waitFor();
			await clickOrditoButton(window, 'Home');
			await shell.locator('.ordito-project-home').waitFor();
			assert.equal(await shell.locator('.ordito-home-features').isVisible(), true);
			assert.equal(await shell.locator('.ordito-home-header-actions').getByRole('button', { name: 'System Map', exact: true }).isEnabled(), true);
			await window.screenshot({ path: path.join(evidence, 'home.png') });
			const modifier = process.platform === 'darwin' ? 'Meta' : 'Control';
			await window.keyboard.press(`${modifier}+Shift+P`);
			await window.locator('.quick-input-widget input').fill('>Specsplice: Open Home');
			await window.keyboard.press('Enter');
			await shell.locator('.ordito-project-home').waitFor();
			await openModelFile(window, modelFile);
			await chooseOrditoDiagram(window, 'Checkout Structure');
			await shell.getByRole('region', { name: 'Diagram: Checkout Structure', exact: true }).waitFor();
			await chooseOrditoDiagram(window, 'Payment Outcome');
			await canvasNode('Payment Declined').press('Enter');
			await harness.app.close();
			harness.app = undefined;
			window = await launch();
			shell = window.locator('.ordito-shell');
			await shell.getByRole('region', { name: 'Diagram: Payment Outcome', exact: true }).waitFor();
			await openProperties(window);
			await shell.locator('.ordito-properties').getByRole('heading', { name: 'Payment Declined', exact: true }).waitFor();
			await openModelFile(window, emptyFile);
			await shell.getByRole('heading', { name: 'Empty System', exact: true }).waitFor();
			assert.equal(await shell.locator('.ordito-node').count(), 0);
			await openModelFile(window, invalidFile);
			const versionError = 'Model version 99 is not supported. Supported model versions are 1, 2, 3, 4 and 5.';
			await shell.getByRole('alert', { name: 'Could Not Open the Project' }).waitFor();
			await revealOrditoText(window, versionError);
			assert.equal(await shell.locator('.ordito-node').count(), 0);
			await shell.getByRole('button', { name: 'Retry', exact: true }).click();
			await revealOrditoText(window, versionError);
			await writeFile(invalidFile, JSON.stringify(checkoutModel));
			await shell.getByRole('region', { name: 'Diagram: Checkout Structure', exact: true }).waitFor();
			const changed = structuredClone(checkoutModel);
			changed.views[0].name = 'Updated Purchase Diagram';
			await writeFile(invalidFile, JSON.stringify(changed));
			await shell.getByRole('region', { name: 'Diagram: Updated Purchase Diagram', exact: true }).waitFor();
			await window.screenshot({ path: path.join(evidence, 'external-update.png') });
			console.log('PASS: native sidebar, cross-feature diagrams, canvas, keyboard selection, technical views and persisted diagram context.');
			console.log('PASS: file model restore, empty model, validation error, retry and correlated external update.');
			await clickOrditoButton(window, 'Home');
			const newFolder = path.join(workspace, 'new-system');
			await mkdir(newFolder);
			await clickOrditoButton(window, 'Create Project');
			await enterValue(window, 'Name', 'New Checkout');
			const enteredWorkspace = window.waitForEvent('domcontentloaded', { timeout: 90000 });
			await chooseFolder(window, newFolder);
			await enteredWorkspace;
			// Create Project enters this workspace; restart the selected folder, as the desktop normally does.
			args[1] = newFolder;
			await shell.getByRole('heading', { name: 'New Checkout', exact: true }).waitFor();
			await shell.getByRole('button', { name: 'Create First Feature', exact: true }).click();
			await enterValue(window, 'Name', 'Confirm Purchase');
			await shell.getByRole('region', { name: 'Diagram: Confirm Purchase · Structure', exact: true }).waitFor();
			await addElement(window, 'Actor', 'Customer');
			await addElement(window, 'Interface', 'Checkout');
			await addElement(window, 'Controller', 'Confirm Order');
			await addElement(window, 'Resource', 'Order');
			await connect(window, 'Customer', 'Checkout', 'Invocation', 'Confirm Purchase', '');
			await connect(window, 'Checkout', 'Confirm Order', 'Invocation', 'Submits', '');
			await connect(window, 'Confirm Order', 'Order', 'Write', 'Create order', 'payment authorized');
			await chooseOrditoDiagram(window, 'Confirm Purchase · Flow');
			for (const name of ['Request Payment', 'Order Confirmed', 'Payment Declined']) { await addElement(window, 'Action', name); }
			await connect(window, 'Request Payment', 'Order Confirmed', 'Invocation', 'Confirm Order', 'payment authorized');
			await connect(window, 'Request Payment', 'Payment Declined', 'Invocation', 'Shows error', 'payment declined');
			console.log('PASS: creates project, feature, structure and conditional success/refusal flow through native UI.');
			const moved = canvasNode('Order Confirmed');
			await moved.press('Enter');
			const before = await moved.evaluate(element => parseFloat(element.style.left));
			await moved.focus();
			await window.keyboard.press('ArrowRight');
			assert.equal(await moved.evaluate(element => parseFloat(element.style.left)), before + 20);
			await window.keyboard.press(`${modifier}+z`);
			assert.equal(await moved.evaluate(element => parseFloat(element.style.left)), before);
			await shell.getByRole('button', { name: 'Redo', exact: true }).click();
			assert.equal(await moved.evaluate(element => parseFloat(element.style.left)), before + 20);
			const zoomBefore = await shell.locator('.ordito-canvas-content').evaluate(element => new DOMMatrixReadOnly(getComputedStyle(element).transform).a);
			await clickOrditoButton(window, 'Zoom Out');
			const zoomAfter = await shell.locator('.ordito-canvas-content').evaluate(element => new DOMMatrixReadOnly(getComputedStyle(element).transform).a);
			assert.ok(Math.abs(zoomAfter - zoomBefore / 1.2) < 0.000001, 'Zoom Out scales the current camera by 1 / 1.2');
			await clickOrditoButton(window, 'Reset Zoom');
			await closeCanvasActions(window);
			const closeProperties = shell.getByRole('button', { name: 'Close Properties', exact: true });
			if (await closeProperties.isVisible()) { await closeProperties.click(); }
			await moved.focus();
			const bounds = await moved.boundingBox(); assert.ok(bounds);
			await window.mouse.move(bounds.x + 40, bounds.y + 40);
			await window.mouse.down();
			await window.mouse.move(bounds.x + 64, bounds.y + 72, { steps: 5 });
			await window.mouse.up();
			await canvasNode('Payment Declined').press('Enter');
			await clickOrditoButton(window, 'Delete Element');
			await window.locator('.monaco-dialog-box').getByRole('button', { name: 'Delete', exact: true }).click();
			assert.equal(await shell.locator('.ordito-canvas .ordito-node').count(), 2);
			await shell.getByRole('button', { name: 'Undo', exact: true }).click();
			await shell.locator('.ordito-canvas').getByRole('button', { name: 'Payment Declined', exact: true }).waitFor();
			await window.keyboard.press(`${modifier}+s`);
			await shell.getByText('Model Saved Locally', { exact: true }).waitFor();
			const projectFile = path.join(newFolder, '.ordito/model.json');
			const saved = JSON.parse(await readFile(projectFile, 'utf8'));
			assert.deepEqual(validateSemanticModel(saved), []);
			assert.equal(saved.version, 4);
			assert.equal(saved.views.length, 2);
			assert.equal(saved.semantics.relations.length, 5);
			const flow = saved.views.find((view: ModelView) => view.kind === 'activity');
			const confirmed = saved.semantics.elements.find((element: SemanticElement) => element.name === 'Order Confirmed');
			assert.deepEqual(flow.nodes.find((node: ModelView['nodes'][number]) => node.elementId === confirmed.id), { elementId: confirmed.id, x: 304, y: 32 });
			assert.equal(await window.locator('.tabs-container .tab').filter({ hasText: 'model.json' }).count(), 0);
			await window.screenshot({ path: path.join(evidence, 'visual-editing.png') });
			await harness.app.close();
			harness.app = undefined;
			window = await launch();
			shell = window.locator('.ordito-shell');
			await shell.getByRole('region', { name: 'Diagram: Confirm Purchase · Flow', exact: true }).waitFor();
			await canvasNode('Request Payment').press('Enter');
			await clickOrditoButton(window, 'Rename Element');
			await enterValue(window, 'Name', 'Updated Payment');
			await shell.locator('.ordito-canvas').getByRole('button', { name: 'Updated Payment', exact: true }).waitFor();
			await shell.getByText('Unsaved Model Changes', { exact: true }).waitFor();
			const external = structuredClone(saved);
			external.name = 'External system';
			await writeFile(projectFile, JSON.stringify(external));
			await shell.getByRole('button', { name: 'Save', exact: true }).click();
			await shell.getByRole('alert', { name: 'Could Not Save the Project' }).waitFor();
			assert.equal(JSON.parse(await readFile(projectFile, 'utf8')).name, 'External system');
			console.log('PASS: native undo/redo, keyboard move, node drag, zoom, safe deletion, save/reopen and external save conflict.');
			await harness.app.close();
			harness.app = undefined;
			window = await launch();
			shell = window.locator('.ordito-shell');
			await shell.locator('.ordito-canvas').getByRole('button', { name: 'Updated Payment', exact: true }).waitFor();
			await shell.getByText('Unsaved Model Changes', { exact: true }).waitFor();
			assert.equal(JSON.parse(await readFile(projectFile, 'utf8')).name, 'External system');
			assert.equal(await window.locator('.tabs-container .tab').filter({ hasText: 'model.json' }).count(), 0);
			await clickOrditoButton(window, 'Reload Project');
			await window.locator('.monaco-dialog-box').getByRole('button', { name: 'Reload', exact: true }).click();
			await clickOrditoButton(window, 'Return to Model');
			await shell.locator('.ordito-project-menu > summary').getByText('External system', { exact: true }).waitFor();
			await shell.getByText('Model Saved Locally', { exact: true }).waitFor();
			console.log('PASS: unsaved backup recovery reopens the visual editor, with external file intact and explicit discard/reload.');
			await canvasNode('Request Payment').press('Enter');
			await clickOrditoButton(window, 'Rename Element');
			await enterValue(window, 'Name', 'Payment in Copy');
			await shell.locator('.ordito-canvas').getByRole('button', { name: 'Payment in Copy', exact: true }).waitFor();
			await shell.getByText('Unsaved Model Changes', { exact: true }).waitFor();
			await clickOrditoButton(window, 'Save Project Copy');
			const copyPicker = window.locator('.quick-input-widget');
			await copyPicker.getByText('Save Project Copy', { exact: true }).waitFor();
			const copyFile = path.join(newFolder, 'copy.ordito.json');
			await copyPicker.locator('input:visible').fill(newFolder + path.sep);
			await copyPicker.getByText('.ordito', { exact: true }).waitFor();
			await copyPicker.locator('input:visible').fill(copyFile);
			await copyPicker.getByRole('button', { name: 'OK', exact: true }).click();
			await copyPicker.waitFor({ state: 'hidden' });
			await clickOrditoButton(window, 'Return to Model');
			await shell.getByText('Model Saved Locally', { exact: true }).waitFor();
			assert.deepEqual(JSON.parse(await readFile(projectFile, 'utf8')), external, 'Save Copy preserves the source document');
			assert.ok(JSON.parse(await readFile(copyFile, 'utf8')).semantics.elements.some((element: SemanticElement) => element.name === 'Payment in Copy'));
			await harness.app.close();
			harness.app = undefined;
			window = await launch();
			await window.locator('.ordito-canvas').getByRole('button', { name: 'Payment in Copy', exact: true }).waitFor();
			assert.equal(await window.locator('.tabs-container .tab').filter({ hasText: 'copy.ordito.json' }).count(), 0);
			console.log('PASS: Save Project Copy preserves the original and restores the saved copy in the visual editor.');

			await harness.app.close();
			harness.app = undefined;
		}
	};
}
